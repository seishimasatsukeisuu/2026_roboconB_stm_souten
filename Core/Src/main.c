  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_CAN_Init();
  MX_USART2_UART_Init();
  MX_TIM2_Init();
  /* USER CODE BEGIN 2 */
  // CANスタート
  HAL_CAN_Start(&hcan);
  // 割り込み有効
  HAL_CAN_ActivateNotification(&hcan, CAN_IT_RX_FIFO0_MSG_PENDING);

  HAL_TIM_PWM_Start(&htim2, TIM_CHANNEL_2);
  HAL_TIM_PWM_Start(&htim2, TIM_CHANNEL_4);

  uint32_t motor_start_time = 0;
  uint32_t switch_on = 0;
  uint8_t motor_running = 0;

  __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_2, 0);
  __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_4, 0);
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    uint8_t local_buf[8];

    if (can_updated)
    {
      __disable_irq();
      memcpy(local_buf, (const void *)can_buf, 8);
      can_updated = 0;
      __enable_irq();

      if (local_buf[0] == 1)
      {
        // 装填開始
        souten_state = SOUTEN;
      }
      else if (local_buf[0] == 0)
      {
        // 停止命令（緊急停止を含む）
        souten_state = SOUTEN_IDLE;
      }
    }

    if (souten_state == SOUTEN)
    {
      // PA7：未押下ならSET、押下ならRESET
      if (HAL_GPIO_ReadPin(GPIOA, GPIO_PIN_7) == GPIO_PIN_SET)
      {
        HAL_GPIO_WritePin(GPIOA, GPIO_PIN_0, GPIO_PIN_SET);
        HAL_GPIO_WritePin(GPIOA, GPIO_PIN_4, GPIO_PIN_SET);
        __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_2, 2000);
        __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_4, 2000);
      }
      else
      {
        // リミットスイッチに到達したので停止
        __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_2, 0);
        __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_4, 0);
        souten_state = SOUTEN_READY;
      }
    }
    else
    {
      __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_2, 0);
      __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_4, 0);
    }
  }
  /* USER CODE END 3 */
